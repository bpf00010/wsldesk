/// Embedded US-QWERTY XKB keymap, FULLY RESOLVED (no include directives):
/// generated by the real libxkbcommon (`xkb_keymap_new_from_names(evdev,
/// pc105, us)`) once at build time and baked in as text.
///
/// Why a real compiled keymap and not a hand-written snippet: wlroots
/// `mmap`s the memfd and hands the bytes straight to
/// `xkb_keymap_new_from_string()`; when parsing fails it posts
/// `wl_resource_post_no_memory()` — surfacing as the misleading
/// "Protocol error 2 on object wl_display@1: no memory". A resolved keymap
/// parses deterministically and covers every US-QWERTY key (shifted symbols,
/// F1–F12, arrows, modifiers, Super) exactly like a physical Linux keyboard.
const US_XKB_KEYMAP: &[u8] = include_bytes!("us_keymap.xkb");

/// `zwp_virtual_keyboard_v1::keymap` format: XKB v1 (the wire value; the
/// protocol does not name an enum for it).
const KEYMAP_FORMAT_XKB_V1: u32 = 1;

