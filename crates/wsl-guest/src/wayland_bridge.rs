/// The compositor writes into this mapping until the screencopy frame is ready.
/// Keep one allocation per output layout. A timed-out copy retires its buffer.
struct ReusableShmBuffer {
    _memfd: std::os::fd::OwnedFd,
    map: std::ptr::NonNull<std::ffi::c_void>,
    len: usize,
    pool: wl_shm_pool::WlShmPool,
    buffer: wl_buffer::WlBuffer,
    layout: (u32, u32, u32, wl_shm::Format),
}

impl ReusableShmBuffer {
    fn new(
        shm: &wl_shm::WlShm,
        qh: &QueueHandle<SessionState>,
        layout: (u32, u32, u32, wl_shm::Format),
    ) -> anyhow::Result<Self> {
        let (width, height, stride, format) = layout;
        let row = width.checked_mul(4).ok_or_else(|| anyhow::anyhow!("invalid capture width"))?;
        let len = u64::from(stride) * u64::from(height);
        anyhow::ensure!(stride >= row && len > 0 && len <= i32::MAX as u64, "invalid capture layout");
        let len = len as usize;
        let memfd = nix::sys::memfd::memfd_create(
            c"wsldesk-frame",
            nix::sys::memfd::MFdFlags::MFD_CLOEXEC,
        )?;
        nix::unistd::ftruncate(&memfd, len as i64)?;
        let map = unsafe {
            nix::sys::mman::mmap(
                None,
                std::num::NonZeroUsize::new(len).expect("validated non-zero size"),
                nix::sys::mman::ProtFlags::PROT_READ,
                nix::sys::mman::MapFlags::MAP_SHARED,
                &memfd,
                0,
            )?
        };
        let pool = shm.create_pool(memfd.as_fd(), len as i32, qh, ());
        let buffer = pool.create_buffer(0, width as i32, height as i32, stride as i32, format, qh, ());
        eprintln!("wsldesk-guest video: allocated capture pool {width}x{height} stride={stride} ({len} bytes)");
        Ok(Self { _memfd: memfd, map, len, pool, buffer, layout })
    }
}

impl Drop for ReusableShmBuffer {
    fn drop(&mut self) {
        self.buffer.destroy();
        self.pool.destroy();
        // SAFETY: this mapping is owned by the buffer and borrowed only
        // while packing and encoding a completed frame.
        let _ = unsafe { nix::sys::mman::munmap(self.map, self.len) };
    }
}

type RawFrame<'a> = (u32, u32, PixelFormat, u16, &'a [u8]);

/// Rate-limited diagnostic for skipped capture frames — a stalled screencopy
/// wait can never again be silent (the zero-frame 10s stall was invisible).
fn log_rate_limited_skip(stage: &str, state: &SessionState) {
    use std::sync::atomic::AtomicU64;
    static LAST_SKIP_LOG: AtomicU64 = AtomicU64::new(0);
    let now_ms = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let last = LAST_SKIP_LOG.load(Ordering::SeqCst);
    if now_ms.saturating_sub(last) >= 5 {
        LAST_SKIP_LOG.store(now_ms, Ordering::SeqCst);
        eprintln!(
            "wsldesk-guest video: screencopy frame skipped at {stage} (width={} height={} \
             stride={} format={:?} failed={}) — output may be mid-reconfiguration",
            state.width, state.height, state.stride, state.format, state.failed
        );
    }
}

struct PendingCapture {
    frame: ZwlrScreencopyFrameV1,
    // None until the buffer is submitted; true for a damage-waiting copy.
    damage_copy: Option<bool>,
    deadline: Instant,
}

impl Drop for PendingCapture {
    fn drop(&mut self) {
        self.frame.destroy();
    }
}

fn begin_capture(state: &mut SessionState, qh: &QueueHandle<SessionState>) -> anyhow::Result<PendingCapture> {
    let manager = state.screencopy.as_ref().ok_or_else(|| anyhow::anyhow!("missing screencopy manager"))?;
    let output = state.outputs.first().ok_or_else(|| anyhow::anyhow!("missing capture output"))?;

    state.width = 0;
    state.height = 0;
    state.stride = 0;
    state.format = None;
    state.ready = false;
    state.failed = false;
    state.buffer_done = false;
    state.damage_rects.clear();
    Ok(PendingCapture {
        // Include the guest cursor in the image and its motion in the damage.
        frame: manager.capture_output(1, output, qh, ()),
        damage_copy: None,
        deadline: Instant::now() + COPY_DEADLINE,
    })
}

fn advance_capture<'a>(
    state: &'a mut SessionState,
    pending: &mut Option<PendingCapture>,
    qh: &QueueHandle<SessionState>,
) -> anyhow::Result<Option<RawFrame<'a>>> {
    let Some(request) = pending.as_mut() else { return Ok(None); };
    if state.failed || (!state.ready && request.damage_copy != Some(true) && Instant::now() >= request.deadline) {
        log_rate_limited_skip("capture", state);
        *pending = None;
        state.capture_buffer = None;
        state.first_frame_sent_for_layout = false;
        return Ok(None);
    }

    if request.damage_copy.is_none() {
        let version = request.frame.version();
        if !(if version >= 3 { state.buffer_done } else { state.width != 0 }) {
            return Ok(None);
        }
        let format = state.format.ok_or_else(|| anyhow::anyhow!("screencopy advertised no shm format"))?;
        let layout = (state.width, state.height, state.stride, format);
        if state.capture_buffer.as_ref().is_none_or(|buffer| buffer.layout != layout) {
            state.capture_buffer = None;
            state.first_frame_sent_for_layout = false;
            let shm = state.shm.as_ref().ok_or_else(|| anyhow::anyhow!("missing wl_shm"))?;
            state.capture_buffer = Some(ReusableShmBuffer::new(shm, qh, layout)?);
        }
        let buffer = &state.capture_buffer.as_ref().expect("capture buffer initialized").buffer;
        let damage_copy = state.first_frame_sent_for_layout && version >= 2;
        if damage_copy {
            request.frame.copy_with_damage(buffer);
        } else {
            request.frame.copy(buffer);
        }
        request.damage_copy = Some(damage_copy);
        request.deadline = Instant::now() + COPY_DEADLINE;
        return Ok(None);
    }

    if !state.ready {
        return Ok(None);
    }
    let damage_copy = request.damage_copy == Some(true);
    *pending = None;
    let rects = &state.damage_rects;
    if damage_copy && rects.is_empty() {
        return Ok(None);
    }
    let buffer = state.capture_buffer.as_ref().expect("completed capture has a buffer");
    let (width, height, stride, format) = buffer.layout;
    let pixel_format = crate::capture::map_pixel_format(format)?;
    // SAFETY: Ready guarantees the compositor has finished writing. The
    // returned borrow is consumed before another frame is submitted.
    let pixels = unsafe { std::slice::from_raw_parts(buffer.map.as_ptr().cast::<u8>(), buffer.len) };
    let stride = stride as usize;
    let area: u64 = rects.iter().map(|r| u64::from(r.width) * u64::from(r.height)).sum();
    let use_rects = damage_copy
        && rects.len() <= usize::from(MAX_DIRTY_RECTS)
        && area * 5 <= u64::from(width) * u64::from(height) * 3;
    let scratch = &mut state.capture_scratch;
    if use_rects {
        scratch.clear();
        for rect in rects {
            scratch.extend_from_slice(&rect.to_bytes());
        }
        for rect in rects {
            let x = rect.x as usize * 4;
            let row_len = rect.width as usize * 4;
            for y in rect.y..rect.y + rect.height {
                let offset = y as usize * stride + x;
                scratch.extend_from_slice(&pixels[offset..offset + row_len]);
            }
        }
        return Ok(Some((width, height, pixel_format, rects.len() as u16, scratch)));
    }

    let row = width as usize * 4;
    let packed = if stride == row {
        pixels
    } else {
        scratch.clear();
        scratch.reserve(row * height as usize);
        for padded_row in pixels.chunks_exact(stride) {
            scratch.extend_from_slice(&padded_row[..row]);
        }
        scratch
    };
    Ok(Some((width, height, pixel_format, 0, packed)))
}

/// Connect to the compositor's wayland socket, retrying briefly (up to
/// 500ms) in case of startup race; on final failure, surface the
/// compositor.log tail so ECONNREFUSED-type crashes are diagnosable.
fn connect_compositor_socket(socket_path: &Path) -> anyhow::Result<std::os::unix::net::UnixStream> {
    let deadline = Instant::now() + Duration::from_millis(500);
    loop {
        match std::os::unix::net::UnixStream::connect(socket_path) {
            Ok(stream) => return Ok(stream),
            Err(err) => {
                if Instant::now() >= deadline {
                    let log_path = socket_path.with_file_name("compositor.log");
                    let log_tail = std::fs::read_to_string(&log_path)
                        .map(|text| {
                            let lines: VecDeque<&str> = text.lines().rev().take(6).collect();
                            lines.into_iter().rev().collect::<Vec<_>>().join(" | ")
                        })
                        .unwrap_or_else(|_| "<no compositor.log>".into());
                    anyhow::bail!(
                        "cannot connect to compositor socket {} after 500ms: {err}; \
                         compositor.log tail: {}",
                        socket_path.display(),
                        log_tail
                    );
                }
                std::thread::sleep(Duration::from_millis(50));
            }
        }
    }
}

