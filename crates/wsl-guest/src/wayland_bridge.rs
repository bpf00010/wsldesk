impl Dispatch<ZwlrDataControlDeviceV1, ()> for SessionState {
    // The `data_offer` event (opcode 0) creates a child offer object.
    wayland_client::event_created_child!(SessionState, ZwlrDataControlDeviceV1, [
        0 => (ZwlrDataControlOfferV1, ()),
    ]);
    fn event(
        state: &mut Self,
        _: &ZwlrDataControlDeviceV1,
        event: zwlr_data_control_device_v1::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        match event {
            zwlr_data_control_device_v1::Event::DataOffer { id: offer } => {
                state.pending_offer = Some((offer, Vec::new()));
            }
            zwlr_data_control_device_v1::Event::Selection { id: offer } => {
                // Move the newest pending offer (with its accumulated mimes)
                // into selection_ready — the main loop performs the actual
                // receive (pipe reads need the queue + can block briefly).
                let mimes = state
                    .pending_offer
                    .take()
                    .map(|(_, mimes)| mimes)
                    .unwrap_or_default();
                if let Some(offer) = offer {
                    state.selection_ready = Some((offer, mimes));
                }
            }
            _ => {}
        }
    }
}

impl Dispatch<ZwlrDataControlOfferV1, ()> for SessionState {
    fn event(
        state: &mut Self,
        offer: &ZwlrDataControlOfferV1,
        event: zwlr_data_control_offer_v1::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        if let zwlr_data_control_offer_v1::Event::Offer { mime_type } = event {
            if let Some((stored, mimes)) = &mut state.pending_offer {
                if stored == offer {
                    mimes.push(mime_type);
                }
            }
        }
    }
}

impl Dispatch<ZwlrDataControlSourceV1, ()> for SessionState {
    fn event(
        state: &mut Self,
        source: &ZwlrDataControlSourceV1,
        event: zwlr_data_control_source_v1::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        match event {
            zwlr_data_control_source_v1::Event::Send { fd, mime_type } => {
                if let Some((_, data, stored_mime)) = &state.active_source {
                    if (mime_type == *stored_mime || mime_type == CLIPBOARD_MIME)
                        && state.clipboard_writes.len() < 16
                        && set_nonblocking(&fd).is_ok()
                    {
                        state.clipboard_writes.push((fd, data.clone(), 0, Instant::now()));
                    }
                }
            }
            zwlr_data_control_source_v1::Event::Cancelled => {
                if let Some((active, _, _)) = &state.active_source {
                    if active == source {
                        state.active_source = None;
                    }
                }
            }
            _ => {}
        }
    }
}
