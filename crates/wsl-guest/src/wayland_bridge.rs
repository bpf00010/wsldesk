fn sha256_hex(bytes: &[u8]) -> String {
    let digest = Sha256::digest(bytes);
    hex::encode(digest)
}

/// Entry point called by the video server thread: runs the unified session
/// loop until `running` goes false or a fatal error occurs.
pub fn run_session_loop(
    socket_path: PathBuf,
    mut stream: &VsockStream,
    running: &Arc<AtomicBool>,
    mut channels: SessionChannels,
    width: u32,
    height: u32,
    scale_milli: u32,
) -> anyhow::Result<()> {
    let socket = connect_compositor_socket(&socket_path)?;
    let conn = Connection::from_socket(socket)
        .map_err(|e| anyhow::anyhow!("wayland connection failed: {e}"))?;
    let mut queue = conn.new_event_queue();
    let qh = queue.handle();
    let display = conn.display();
    let _registry = display.get_registry(&qh, ());

    let mut state = SessionState {
        outputs: Vec::new(),
        shm: None,
        screencopy: None,
        width: 0,
        height: 0,
        stride: 0,
        format: None,
        ready: false,
        failed: false,
        buffer_done: false,
        first_frame_sent_for_layout: false,
        damage_rects: Vec::with_capacity(usize::from(MAX_DIRTY_RECTS) + 1),
        seat: None,
        kb_manager: None,
        keyboard: None,
        keymap_sent: false,
        ptr_manager: None,
        pointer: None,
        input: InputState::default(),
        telemetry: InputTelemetry::default(),
        output_manager: None,
        heads: Vec::new(),
        serial: None,
        pending_resize: Some((width, height, scale_milli, channels.refresh_mhz)),
        capture_buffer: None,
        capture_scratch: Vec::new(),
        refresh_mhz: channels.refresh_mhz.clamp(30_000, 240_000),
        data_control: None,
        data_device: None,
        pending_offer: None,
        selection_ready: None,
        active_source: None,
        clipboard_read: None,
        clipboard_writes: Vec::new(),
        last_host_offered_hash: String::new(),
        last_guest_sent_hash: String::new(),
    };

    conn.flush().ok();
    queue.roundtrip(&mut state)?;

    // Sanity checks with actionable messages.
    if state.screencopy.is_none() {
        anyhow::bail!(
            "compositor does not expose zwlr_screencopy_manager_v1 — capture is wlroots-only \
             in 4A (sway/hyprland/river/wayfire/labwc); weston needs the portal path"
        );
    }
    if state.shm.is_none() {
        anyhow::bail!("compositor does not expose wl_shm");
    }
    if state.outputs.is_empty() {
        anyhow::bail!("compositor advertises no wl_output (headless backend output missing?)");
    }

    // Create the input devices now that the seat is bound.
    ensure_input_devices(&mut state, &qh);
    // Ship the embedded keymap once (memfd, pure Rust — zero libxkbcommon).
    if let Some(keyboard) = &state.keyboard {
        upload_keymap(keyboard, &conn)?;
        state.keymap_sent = true;
    }

    // Nonblocking wayland socket (pollable fd from the backend).
    let wl_fd = conn.backend().poll_fd().as_raw_fd();
    let _ = nix::fcntl::fcntl(
        // SAFETY: wl_fd is the connection socket owned by `conn`.
        unsafe { BorrowedFd::borrow_raw(wl_fd) },
        nix::fcntl::FcntlArg::F_SETFL(nix::fcntl::OFlag::O_NONBLOCK),
    );

    eprintln!(
        "wsldesk-guest video: session loop start (socket={}, outputs={}, keyboard+pointer ready, keymap shipped)",
        socket_path.display(),
        state.outputs.len()
    );

    let mut frame_id: u64 = 0;
    let mut next_frame_at = Instant::now();
    let mut pending_capture = None;
    let mut last_report = Instant::now();
    let mut last_telemetry = Instant::now();
    let mut frames_reported: u64 = 0;
    let mut bytes_reported: u64 = 0;

    loop {
        if !running.load(Ordering::SeqCst) {
            return Ok(());
        }

        // 1. Drain pending wayland events without blocking.
        dispatch_pending_all(&conn, &mut queue, &mut state)?;

        // Keep control input moving even if a damage request waits indefinitely.
        while let Ok(msg) = channels.input_rx.try_recv() {
            apply_control_message(&mut state, &qh, &conn, msg);
        }
        if state.serial.is_some() && state.pending_resize.is_some() {
            if pending_capture.take().is_some() {
                state.capture_buffer = None;
            }
            state.first_frame_sent_for_layout = false;
            apply_output_mode(&mut state, &qh);
            next_frame_at = Instant::now();
        }

        // 4. Handle a compositor selection (guest clipboard → host).
        if let Some((offer, mimes)) = state.selection_ready.take() {
            receive_clipboard_offer(
                &mut state,
                &conn,
                &offer,
                &mimes,
            )?;
        }
        pump_clipboard(&mut state, &channels.clipboard_tx);

        // 5. Frame pacing + capture.
        let now = Instant::now();
        if pending_capture.is_none() && now >= next_frame_at {
            let period = Duration::from_nanos(1_000_000_000_000 / u64::from(state.refresh_mhz));
            next_frame_at += period;
            if next_frame_at <= now {
                // Skip missed slots after a stall instead of rendering a burst.
                next_frame_at = now + period;
            }
            pending_capture = Some(begin_capture(&mut state, &qh)?);
        }
        if let Some((w, h, pixel_format, rect_count, pixels)) =
            advance_capture(&mut state, &mut pending_capture, &qh)?
        {
            let wire_len = if rect_count == 0 {
                let bytes = crate::capture::encode_video_frame(frame_id, w, h, pixel_format, pixels)?;
                stream.write_all(&bytes)?;
                bytes.len()
            } else {
                let compressed = lz4_flex::compress_prepend_size(pixels);
                let header = VideoFrameHeader {
                    frame_id, width: w, height: h, stride: w * 4, pixel_format,
                    compression: FrameCompression::Lz4, rect_count,
                    payload_len: compressed.len().try_into()?,
                }.to_bytes();
                stream.write_all(&header)?;
                stream.write_all(&compressed)?;
                header.len() + compressed.len()
            };
            stream.flush()?;
            state.first_frame_sent_for_layout = true;
            frame_id += 1;
            frames_reported += 1;
            bytes_reported += wire_len as u64;
        }
        if last_report.elapsed() >= Duration::from_secs(5) && frames_reported > 0 {
            eprintln!(
                "wsldesk-guest video: {frames_reported} frames in 5s, {bytes_reported} bytes sent, res {}x{}",
                state.width, state.height
            );
            frames_reported = 0;
            bytes_reported = 0;
            last_report = Instant::now();
        }

        // Input routing telemetry (rate-limited to every ~2s when active) —
        // confirms live over daemon logs that mouse/key packets reach Wayland.
        if last_telemetry.elapsed() >= Duration::from_secs(2) && state.telemetry.any_activity() {
            let t = state.telemetry.reset();
            eprintln!(
                "input routed: pointer_moves={} buttons={} keys={} resizes={}",
                t.pointer_moves, t.buttons, t.keys, t.resizes
            );
            last_telemetry = Instant::now();
        }

        // 6. Push requests out, then wait for wayland events or the next
        //    frame slot (whichever first). The 2ms slice keeps input latency
        //    negligible without a busy loop.
        conn.flush().ok();
        let until_frame = if pending_capture.is_some() {
            POLL_SLICE
        } else {
            next_frame_at.saturating_duration_since(Instant::now()).min(POLL_SLICE)
        };
        if until_frame.is_zero() {
            continue;
        }
        let mut poll_fds = [nix::poll::PollFd::new(
            unsafe { BorrowedFd::borrow_raw(wl_fd) },
            nix::poll::PollFlags::POLLIN,
        )];
        let timeout = nix::sys::time::TimeSpec::new(0, until_frame.subsec_nanos().into());
        let _ = nix::poll::ppoll(&mut poll_fds, Some(timeout), None);
        if poll_fds[0]
            .revents()
            .is_some_and(|flags| flags.intersects(
                nix::poll::PollFlags::POLLIN | nix::poll::PollFlags::POLLHUP | nix::poll::PollFlags::POLLERR
            ))
        {
            // prepare_read/read: the guard-based safe way to pull bytes off
            // the socket into the internal dispatch queue. WouldBlock just
            // means the event was already drained.
            if let Some(guard) = conn.prepare_read() {
                if let Err(err) = guard.read() {
                    let would_block = match &err {
                        wayland_client::backend::WaylandError::Io(io_err) => {
                            io_err.kind() == std::io::ErrorKind::WouldBlock
                                || io_err.kind() == std::io::ErrorKind::Interrupted
                        }
                        _ => false,
                    };
                    if !would_block {
                        return Err(err.into());
                    }
                }
            }
        }
    }
}

/// Dispatch until the pending queue is empty.
fn dispatch_pending_all(
    _conn: &Connection,
    queue: &mut EventQueue<SessionState>,
    state: &mut SessionState,
) -> anyhow::Result<()> {
    loop {
        let processed = queue.dispatch_pending(state)?;
        if processed == 0 {
            break;
        }
    }
    Ok(())
}

/// Route one inbound control message into the session.
fn apply_control_message(
    state: &mut SessionState,
    qh: &QueueHandle<SessionState>,
    conn: &Connection,
    msg: ControlMessage,
) {
    let time_ms = epoch_ms_low32();
    match msg {
        ControlMessage::InputEvent(InputPayload::Key { code, pressed }) => {
            let modifiers_changed = state.input.apply_key(code, pressed);
            if let Some(keyboard) = &state.keyboard {
                // zwp_virtual_keyboard_v1::key takes RAW Linux evdev keycodes
                // (KEY_ESC = 1, KEY_A = 30, KEY_ENTER = 28, KEY_LEFTMETA =
                // 125) — wlroots adds the +8 XKB offset INTERNALLY. Adding
                // WAYLAND_KEY_OFFSET here double-shifted every key and the
                // compositor saw the wrong keys entirely. Wire state: 1 =
                // pressed, 0 = released.
                if modifiers_changed {
                    // Exact XKB evdev modifier bits:
                    // Shift=0x01, CapsLock=0x02, Ctrl=0x04, Alt/Mod1=0x08,
                    // Super/Mod4=0x40 (see common::keymap MOD_*).
                    keyboard.modifiers(state.input.modifiers & !MOD_CAPSLOCK, 0, state.input.modifiers & MOD_CAPSLOCK, 0);
                }
                keyboard.key(time_ms, code, u32::from(pressed));
                static DEBUG: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
                if *DEBUG.get_or_init(|| std::env::var("WSLDESK_DEBUG_INPUT").as_deref() == Ok("1")) {
                    eprintln!("[GUEST-KB] code={code} pressed={pressed} mods=0x{:02x}", state.input.modifiers);
                }
            }
            state.telemetry.keys += 1;
            if let Err(err) = conn.flush() { eprintln!("keyboard flush: {err}"); }
        }
        ControlMessage::InputEvent(InputPayload::PointerMotion { dx, dy }) => {
            if let Some(pointer) = &state.pointer {
                pointer.motion(time_ms, dx as f64, dy as f64);
                pointer.frame();
            }
            state.telemetry.pointer_moves += 1;
            conn.flush().ok();
        }
        ControlMessage::InputEvent(InputPayload::PointerMotionAbsolute {
            x,
            y,
            width,
            height,
        }) => {
            // Never feed zero extents to motion_absolute — a 0×0 extent is
            // an invalid mapping and compositor-behavior is undefined.
            if width > 0 && height > 0 {
                if let Some(pointer) = &state.pointer {
                    pointer.motion_absolute(time_ms, x, y, width, height);
                    pointer.frame();
                }
            }
            state.telemetry.pointer_moves += 1;
            conn.flush().ok();
        }
        ControlMessage::InputEvent(InputPayload::PointerButton { button, pressed }) => {
            if let Some(pointer) = &state.pointer {
                pointer.button(time_ms, button as u32, button_state(pressed));
                pointer.frame();
            }
            state.telemetry.buttons += 1;
            conn.flush().ok();
        }
        ControlMessage::InputEvent(InputPayload::PointerAxis { vertical, delta }) => {
            if delta == 0 {
                return;
            }
            if let Some(pointer) = &state.pointer {
                let axis = if vertical {
                    Axis::VerticalScroll
                } else {
                    Axis::HorizontalScroll
                };
                // axis_discrete carries both scroll distance and wheel steps.
                // A second event on the same axis can overwrite the distance.
                pointer.axis_source(wayland_client::protocol::wl_pointer::AxisSource::Wheel);
                pointer.axis_discrete(time_ms, axis, f64::from(delta) * 15.0, delta);
                pointer.frame();
            }
            state.telemetry.pointer_moves += 1;
            conn.flush().ok();
        }
        ControlMessage::Resize {
            width,
            height,
            scale_milli,
            refresh_mhz,
        } => {
            state.pending_resize = Some((width, height, scale_milli, refresh_mhz));
            state.telemetry.resizes += 1;
            eprintln!(
                "wsldesk-guest video: Resize queued: {width}x{height} scale_milli={scale_milli}"
            );
        }
        ControlMessage::ClipboardUpdate { mime_type, data } => {
            offer_clipboard_to_session(state, qh, mime_type, data);
        }
        _ => {}
    }
}

fn button_state(pressed: bool) -> ButtonState {
    if pressed {
        ButtonState::Pressed
    } else {
        ButtonState::Released
    }
}

fn epoch_ms_low32() -> u32 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| (d.as_millis() & 0xFFFF_FFFF) as u32)
        .unwrap_or(0)
}

/// Create keyboard/pointer/data-device once a seat is bound.
fn ensure_input_devices(state: &mut SessionState, qh: &QueueHandle<SessionState>) {
    let Some(seat) = state.seat.clone() else {
        return;
    };
    if state.keyboard.is_none() {
        if let Some(manager) = state.kb_manager.clone() {
            state.keyboard = Some(manager.create_virtual_keyboard(&seat, qh, ()));
        }
    }
    if state.pointer.is_none() {
        if let Some(manager) = state.ptr_manager.clone() {
            state.pointer = Some(manager.create_virtual_pointer(Some(&seat), qh, ()));
        }
    }
    if state.data_device.is_none() {
        if let Some(manager) = state.data_control.clone() {
            state.data_device = Some(manager.get_data_device(&seat, qh, ()));
        }
    }
}

/// Upload the embedded US keymap through a memfd (MFD_CLOEXEC) — pure Rust,
/// zero libxkbcommon. The buffer written to the memfd ends with a trailing
/// `\0` (required by `xkb_keymap_new_from_string` in wlroots) and the size
/// passed on the wire INCLUDES that NUL byte.
fn upload_keymap(keyboard: &ZwpVirtualKeyboardV1, _conn: &Connection) -> anyhow::Result<()> {
    // keymap text + trailing NUL terminator (size includes the NUL).
    let mut keymap = US_XKB_KEYMAP.to_vec();
    keymap.push(0u8);
    let memfd = nix::sys::memfd::memfd_create(
        c"wsldesk-xkb-keymap",
        nix::sys::memfd::MFdFlags::MFD_CLOEXEC,
    )
    .map_err(|e| anyhow::anyhow!("keymap memfd_create failed: {e}"))?;
    {
        let mut file =
            std::fs::File::from(memfd.try_clone().map_err(|e| anyhow::anyhow!("{e}"))?);
        file.write_all(&keymap)
            .and_then(|_| file.flush())
            .map_err(|e| anyhow::anyhow!("keymap write failed: {e}"))?;
    }
    nix::unistd::ftruncate(&memfd, keymap.len() as i64)
        .map_err(|e| anyhow::anyhow!("keymap ftruncate failed: {e}"))?;
    keyboard.keymap(KEYMAP_FORMAT_XKB_V1, memfd.as_fd(), keymap.len() as u32);
    eprintln!(
        "wsldesk-guest video: virtual keyboard keymap uploaded ({} bytes + NUL, memfd, evdev+8)",
        keymap.len() - 1
    );
    Ok(())
}

