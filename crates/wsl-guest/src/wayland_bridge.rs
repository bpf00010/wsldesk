/// Host → guest: offer clipboard text to the compositor.
fn offer_clipboard_to_session(
    state: &mut SessionState,
    qh: &QueueHandle<SessionState>,
    mime_type: String,
    data: Vec<u8>,
) {
    let hash = sha256_hex(&data);
    if hash == state.last_host_offered_hash {
        return; // echo loop guard
    }
    let Some(device) = state.data_device.clone() else {
        return;
    };
    let Some(manager) = state.data_control.clone() else {
        return;
    };
    // Replace any active source (its content is superseded).
    if let Some((old_source, _, _)) = state.active_source.take() {
        old_source.destroy();
    }
    let source = manager.create_data_source(qh, ());
    source.offer(CLIPBOARD_MIME.to_string());
    device.set_selection(Some(&source));
    let data_len = data.len();
    state.active_source = Some((source, data.into(), mime_type));
    state.last_host_offered_hash = hash;
    eprintln!("wsldesk-guest video: clipboard offered to session ({data_len} bytes)");
}

/// Guest → host: read a selected offer's text payload through a pipe
/// (flushing/dispatching so the compositor can serve the receive request)
/// and decide whether it must be shipped (dedup against the last payload WE
/// offered, so pasting the same text back and forth never loops).
fn receive_clipboard_offer(
    state: &mut SessionState,
    conn: &Connection,
    offer: &ZwlrDataControlOfferV1,
    mimes: &[String],
) -> anyhow::Result<()> {
    state.clipboard_read = None;
    if !mimes.iter().any(|m| m == CLIPBOARD_MIME) {
        return Ok(());
    }
    let (read_fd, write_fd) =
        nix::unistd::pipe().map_err(|e| anyhow::anyhow!("clipboard pipe failed: {e}"))?;
    set_nonblocking(&read_fd)?;
    offer.receive(CLIPBOARD_MIME.to_string(), write_fd.as_fd());
    drop(write_fd);
    conn.flush().ok();
    state.clipboard_read = Some((read_fd, Vec::new(), Instant::now()));
    Ok(())
}

fn set_nonblocking(fd: &std::os::fd::OwnedFd) -> nix::Result<()> {
    use nix::fcntl::{fcntl, FcntlArg, OFlag};
    let flags = OFlag::from_bits_retain(fcntl(fd, FcntlArg::F_GETFL)?);
    fcntl(fd, FcntlArg::F_SETFL(flags | OFlag::O_NONBLOCK))?;
    Ok(())
}

fn pump_clipboard(state: &mut SessionState, clipboard_tx: &tokio::sync::mpsc::Sender<(String, Vec<u8>)>) {
    let timeout = Duration::from_secs(2);
    state.clipboard_writes.retain_mut(|(fd, bytes, offset, progress)| {
        if progress.elapsed() >= timeout { return false; }
        match nix::unistd::write(fd.as_fd(), &bytes[*offset..]) {
            Ok(n) if n > 0 => {
                *offset += n;
                *progress = Instant::now();
                *offset < bytes.len()
            }
            Err(nix::errno::Errno::EAGAIN | nix::errno::Errno::EINTR) => true,
            _ => false,
        }
    });
    let Some((read_fd, mut buf, mut progress)) = state.clipboard_read.take() else { return; };
    if progress.elapsed() >= timeout { return; }
    let mut tmp = [0u8; 8192];
    for _ in 0..32 {
        match nix::unistd::read(read_fd.as_fd(), &mut tmp) {
            Ok(0) => {
                if !buf.is_empty() {
                    let hash = sha256_hex(&buf);
                    if hash != state.last_host_offered_hash && hash != state.last_guest_sent_hash
                        && clipboard_tx.try_send((CLIPBOARD_MIME.to_string(), buf)).is_ok() {
                        state.last_guest_sent_hash = hash;
                    }
                }
                return;
            }
            Ok(n) if buf.len() + n <= 16 * 1024 * 1024 => {
                buf.extend_from_slice(&tmp[..n]);
                progress = Instant::now();
            }
            Err(nix::errno::Errno::EAGAIN | nix::errno::Errno::EINTR) => break,
            _ => return,
        }
    }
    state.clipboard_read = Some((read_fd, buf, progress));
}

