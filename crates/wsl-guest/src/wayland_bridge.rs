/// Clipboard MIME type used both directions.
pub const CLIPBOARD_MIME: &str = "text/plain;charset=utf-8";

/// How long a single screencopy copy may take before we skip the frame.
const COPY_DEADLINE: Duration = Duration::from_millis(200);

/// Poll slice for the nonblocking event loop (input latency bound).
const POLL_SLICE: Duration = Duration::from_millis(4);

/// Embedded US-QWERTY XKB keymap, FULLY RESOLVED (no include directives):
/// generated by the real libxkbcommon (`xkb_keymap_new_from_names(evdev,
/// pc105, us)`) once at build time and baked in as text.
///
/// Why a real compiled keymap and not a hand-written snippet: wlroots
/// `mmap`s the memfd and hands the bytes straight to
/// `xkb_keymap_new_from_string()`; when parsing fails it posts
/// `wl_resource_post_no_memory()` — surfacing as the misleading
/// "Protocol error 2 on object wl_display@1: no memory". A resolved keymap
/// parses deterministically and covers every US-QWERTY key (shifted symbols,
/// F1–F12, arrows, modifiers, Super) exactly like a physical Linux keyboard.
const US_XKB_KEYMAP: &[u8] = include_bytes!("us_keymap.xkb");

/// `zwp_virtual_keyboard_v1::keymap` format: XKB v1 (the wire value; the
/// protocol does not name an enum for it).
const KEYMAP_FORMAT_XKB_V1: u32 = 1;

/// Channels between the daemon (control plane) and this bridge thread.
pub struct SessionChannels {
    /// Inbound from the daemon: `InputEvent` / `Resize` / `ClipboardUpdate`.
    pub input_rx: tokio::sync::mpsc::Receiver<ControlMessage>,
    /// Outbound to the daemon: guest clipboard selections to ship to the host.
    pub clipboard_tx: tokio::sync::mpsc::Sender<(String, Vec<u8>)>,
}

/// Cumulative input state tracked guest-side for
/// `zwp_virtual_keyboard_v1::modifiers`.
#[derive(Debug, Default, Clone, Copy)]
struct InputState {
    modifiers: u32,
    caps_lock: bool,
}

/// Rate-limited input routing counters (item 4 of the 4B input fix).
#[derive(Debug, Default, Clone, Copy)]
struct InputTelemetry {
    pointer_moves: u64,
    buttons: u64,
    keys: u64,
    resizes: u64,
}

impl InputTelemetry {
    fn any_activity(&self) -> bool {
        self.pointer_moves > 0 || self.buttons > 0 || self.keys > 0 || self.resizes > 0
    }

    fn reset(&mut self) -> Self {
        std::mem::take(self)
    }
}

impl InputState {
    /// Apply one key transition; returns `true` when the modifier bitmask
    /// changed and `modifiers()` must be re-sent.
    fn apply_key(&mut self, code: u32, pressed: bool) -> bool {
        let bit = match code {
            common::keymap::KEY_LEFTSHIFT | common::keymap::KEY_RIGHTSHIFT => MOD_SHIFT,
            common::keymap::KEY_LEFTCTRL | common::keymap::KEY_RIGHTCTRL => MOD_CONTROL,
            common::keymap::KEY_LEFTALT | common::keymap::KEY_RIGHTALT => MOD_ALT,
            KEY_LEFTMETA | KEY_RIGHTMETA => MOD_SUPER,
            _ => 0,
        };
        if bit != 0 {
            if pressed {
                self.modifiers |= bit;
            } else {
                self.modifiers &= !bit;
            }
            return true;
        }
        if code == KEY_CAPSLOCK && pressed {
            self.caps_lock = !self.caps_lock;
            self.modifiers = if self.caps_lock {
                self.modifiers | MOD_CAPSLOCK
            } else {
                self.modifiers & !MOD_CAPSLOCK
            };
            return true;
        }
        false
    }
}

/// Everything the unified event loop owns.
