/// Frame data ready to ship: (width, height, stride, format, packed rows).
type RawFrame = (u32, u32, u32, wl_shm::Format, Vec<u8>);

/// Rate-limited diagnostic for skipped capture frames — a stalled screencopy
/// wait can never again be silent (the zero-frame 10s stall was invisible).
fn log_rate_limited_skip(stage: &str, state: &SessionState) {
    use std::sync::atomic::AtomicU64;
    static LAST_SKIP_LOG: AtomicU64 = AtomicU64::new(0);
    let now_ms = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let last = LAST_SKIP_LOG.load(Ordering::SeqCst);
    if now_ms.saturating_sub(last) >= 5 {
        LAST_SKIP_LOG.store(now_ms, Ordering::SeqCst);
        eprintln!(
            "wsldesk-guest video: screencopy frame skipped at {stage} (width={} height={} \
             stride={} format={:?} failed={}) — output may be mid-reconfiguration",
            state.width, state.height, state.stride, state.format, state.failed
        );
    }
}

/// Capture one full frame through `zwlr_screencopy_manager_v1` with
/// `overlay_cursor = 1` (the native Linux cursor is rendered into the
/// stream — single-cursor UX).
fn capture_one_frame(
    state: &mut SessionState,
    conn: &Connection,
    queue: &mut EventQueue<SessionState>,
    qh: &QueueHandle<SessionState>,
) -> anyhow::Result<Option<RawFrame>> {
    let Some(manager) = state.screencopy.clone() else {
        anyhow::bail!("compositor has no zwlr_screencopy_manager_v1");
    };
    let Some(output) = state.outputs.first().cloned() else {
        anyhow::bail!("compositor advertises no wl_output");
    };
    let Some(shm) = state.shm.clone() else {
        anyhow::bail!("compositor advertises no wl_shm");
    };

    state.width = 0;
    state.height = 0;
    state.stride = 0;
    state.format = None;
    state.ready = false;
    state.failed = false;
    // overlay_cursor = 1: render the native cursor into the captured frame.
    let frame = manager.capture_output(1, &output, qh, ());
    // Nonblocking loop: flush the request NOW — pump_events below waits for
    // the compositor's reply, which cannot arrive until the bytes leave.
    conn.flush().ok();

    // Wait for the advertised buffer geometry (nonblocking dispatch + poll).
    // Predicate: the `buffer` event arrived (or the frame failed).
    let deadline = Instant::now() + COPY_DEADLINE;
    while state.width == 0 {
        if state.failed {
            anyhow::bail!("screencopy failed before advertising buffer geometry");
        }
        if Instant::now() >= deadline {
            // Skip this frame (output may be mid-reconfiguration) — never
            // silently: rate-limited diagnostic with the wait stage.
            log_rate_limited_skip("buffer-wait", state);
            frame.destroy();
            return Ok(None);
        }
        pump_events(
            state,
            conn,
            queue,
            Duration::from_millis(2),
            |s| s.width != 0 || s.failed,
        )?;
    }
    let (width, height, stride) = (state.width, state.height, state.stride);
    let Some(format) = state.format else {
        anyhow::bail!("screencopy buffer event carried no format");
    };
    let buffer_len = stride as usize * height as usize;

    let memfd = nix::sys::memfd::memfd_create(
        c"wsldesk-frame",
        nix::sys::memfd::MFdFlags::MFD_CLOEXEC,
    )
    .map_err(|e| anyhow::anyhow!("memfd_create failed: {e}"))?;
    nix::unistd::ftruncate(&memfd, buffer_len as i64)
        .map_err(|e| anyhow::anyhow!("ftruncate failed: {e}"))?;
    let map = unsafe {
        nix::sys::mman::mmap(
            None,
            std::num::NonZeroUsize::new(buffer_len).expect("non-zero buffer"),
            nix::sys::mman::ProtFlags::PROT_READ,
            nix::sys::mman::MapFlags::MAP_SHARED,
            &memfd,
            0,
        )
        .map_err(|e| anyhow::anyhow!("mmap failed: {e}"))?
    };

    let pool = shm.create_pool(memfd.as_fd(), buffer_len as i32, qh, ());
    let buffer = pool.create_buffer(0, width as i32, height as i32, stride as i32, format, qh, ());
    // The buffer holds its own reference to the pool. Release the pool's
    // protocol handle now so every completed buffer can free its mapping.
    pool.destroy();
    frame.copy(&buffer);
    // The pool request carries the memfd fd and `copy` must reach the
    // compositor before the wait below — flush both while the fds are open.
    conn.flush().ok();

    // Wait for the copy (nonblocking; bounded).
    // Predicate: this stage waits for `ready` — NOT for the geometry (which
    // is already set from Wait Loop 1).
    let deadline = Instant::now() + COPY_DEADLINE;
    loop {
        if state.ready {
            break;
        }
        if state.failed {
            frame.destroy();
            buffer.destroy();
            let _ = unsafe { nix::sys::mman::munmap(map, buffer_len) };
            anyhow::bail!("screencopy frame failed");
        }
        if Instant::now() >= deadline {
            let _ = unsafe { nix::sys::mman::munmap(map, buffer_len) };
            log_rate_limited_skip("ready-wait", state);
            frame.destroy();
            buffer.destroy();
            return Ok(None); // skipped (e.g. during output reconfiguration)
        }
        if let Err(err) = pump_events(
            state,
            conn,
            queue,
            Duration::from_millis(2),
            |s| s.ready || s.failed,
        ) {
            frame.destroy();
            buffer.destroy();
            let _ = unsafe { nix::sys::mman::munmap(map, buffer_len) };
            return Err(err);
        }
    }

    let pixels = unsafe { std::slice::from_raw_parts(map.as_ptr() as *const u8, buffer_len) };
    let packed: Vec<u8> = if stride == width * 4 {
        pixels.to_vec()
    } else {
        let row = width as usize * 4;
        let mut packed = Vec::with_capacity(row * height as usize);
        for y in 0..height as usize {
            let start = y * stride as usize;
            packed.extend_from_slice(&pixels[start..start + row]);
        }
        packed
    };
    let _ = unsafe { nix::sys::mman::munmap(map, buffer_len) };
    frame.destroy();
    // Dropping the Rust handle alone leaves the resource alive in Sway.
    buffer.destroy();

    Ok(Some((width, height, stride, format, packed)))
}

/// Nonblocking pump helper: dispatch pending, wait for readability up to
/// `timeout`, pull bytes off the socket, and dispatch again — until `done`
/// reports completion for the caller's wait stage.
///
/// The predicate is what makes this correct for BOTH screencopy wait stages:
/// Wait Loop 1 waits for the `buffer` event (`width != 0`) and Wait Loop 2
/// waits for `ready` — an early return keyed on `width != 0` inside here
/// would starve Wait Loop 2 (seen live as a zero-frame stream with a hot
/// 200ms spin until WSAE10053).
fn pump_events(
    state: &mut SessionState,
    conn: &Connection,
    queue: &mut EventQueue<SessionState>,
    timeout: Duration,
    done: impl Fn(&SessionState) -> bool,
) -> anyhow::Result<()> {
    // 1. Flush outbound requests (ignore WouldBlock — retried next pass).
    conn.flush().ok();
    // 2. Dispatch anything already buffered.
    dispatch_pending_all(conn, queue, state)?;
    // 3. Done? (checked by the caller's stage predicate)
    if done(state) {
        return Ok(());
    }
    // 4. Prepare-read + poll: wait for the compositor to send something.
    let fd = conn.backend().poll_fd().as_raw_fd();
    let mut fds = [nix::poll::PollFd::new(
        // SAFETY: fd owned by `conn`, alive for this call.
        unsafe { BorrowedFd::borrow_raw(fd) },
        nix::poll::PollFlags::POLLIN,
    )];
    let poll_timeout =
        nix::poll::PollTimeout::try_from(timeout).unwrap_or(nix::poll::PollTimeout::ZERO);
    let _ = nix::poll::poll(&mut fds, poll_timeout);
    let readable = fds[0]
        .revents()
        .is_some_and(|flags| flags.contains(nix::poll::PollFlags::POLLIN));
    match readable {
        // Not readable within the slice — cancel the prepared read cleanly.
        false => return Ok(()),
        true => {
            if let Some(guard) = conn.prepare_read() {
                let result = guard.read();
                match result {
                    Ok(_) => {}
                    Err(err) => {
                        let transient = match &err {
                            wayland_client::backend::WaylandError::Io(io_err) => {
                                io_err.kind() == std::io::ErrorKind::WouldBlock
                                    || io_err.kind() == std::io::ErrorKind::Interrupted
                            }
                            _ => false,
                        };
                        if !transient {
                            return Err(err.into());
                        }
                    }
                }
            }
        }
    }
    // 5. CRITICAL: `read` pulled bytes into the internal event queue but does
    // NOT dispatch them — without this second dispatch pass the screencopy
    // `buffer`/`ready` events never reach our Dispatch impls.
    dispatch_pending_all(conn, queue, state)?;
    Ok(())
}

/// Connect to the compositor's wayland socket, retrying briefly (up to
/// 500ms) in case of startup race; on final failure, surface the
/// compositor.log tail so ECONNREFUSED-type crashes are diagnosable.
fn connect_compositor_socket(socket_path: &Path) -> anyhow::Result<std::os::unix::net::UnixStream> {
    let deadline = Instant::now() + Duration::from_millis(500);
    loop {
        match std::os::unix::net::UnixStream::connect(socket_path) {
            Ok(stream) => return Ok(stream),
            Err(err) => {
                if Instant::now() >= deadline {
                    let log_path = socket_path.with_file_name("compositor.log");
                    let log_tail = std::fs::read_to_string(&log_path)
                        .map(|text| {
                            let lines: VecDeque<&str> = text.lines().rev().take(6).collect();
                            lines.into_iter().rev().collect::<Vec<_>>().join(" | ")
                        })
                        .unwrap_or_else(|_| "<no compositor.log>".into());
                    anyhow::bail!(
                        "cannot connect to compositor socket {} after 500ms: {err}; \
                         compositor.log tail: {}",
                        socket_path.display(),
                        log_tail
                    );
                }
                std::thread::sleep(Duration::from_millis(50));
            }
        }
    }
}

