/// Cumulative input state tracked guest-side for
/// `zwp_virtual_keyboard_v1::modifiers`.
#[derive(Debug, Default, Clone, Copy)]
struct InputState {
    modifiers: u32,
    caps_lock: bool,
}

/// Rate-limited input routing counters (item 4 of the 4B input fix).
#[derive(Debug, Default, Clone, Copy)]
struct InputTelemetry {
    pointer_moves: u64,
    buttons: u64,
    keys: u64,
    resizes: u64,
}

impl InputTelemetry {
    fn any_activity(&self) -> bool {
        self.pointer_moves > 0 || self.buttons > 0 || self.keys > 0 || self.resizes > 0
    }

    fn reset(&mut self) -> Self {
        std::mem::take(self)
    }
}

impl InputState {
    /// Apply one key transition; returns `true` when the modifier bitmask
    /// changed and `modifiers()` must be re-sent.
    fn apply_key(&mut self, code: u32, pressed: bool) -> bool {
        let bit = match code {
            common::keymap::KEY_LEFTSHIFT | common::keymap::KEY_RIGHTSHIFT => MOD_SHIFT,
            common::keymap::KEY_LEFTCTRL | common::keymap::KEY_RIGHTCTRL => MOD_CONTROL,
            common::keymap::KEY_LEFTALT | common::keymap::KEY_RIGHTALT => MOD_ALT,
            KEY_LEFTMETA | KEY_RIGHTMETA => MOD_SUPER,
            _ => 0,
        };
        if bit != 0 {
            if pressed {
                self.modifiers |= bit;
            } else {
                self.modifiers &= !bit;
            }
            return true;
        }
        if code == KEY_CAPSLOCK && pressed {
            self.caps_lock = !self.caps_lock;
            self.modifiers = if self.caps_lock {
                self.modifiers | MOD_CAPSLOCK
            } else {
                self.modifiers & !MOD_CAPSLOCK
            };
            return true;
        }
        false
    }
}

