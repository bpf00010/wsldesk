//! Guest-side Wayland session bridge (Plan.Md §5 M4B).
//!
//! One Wayland connection (to the isolated compositor) carries everything:
//!
//! - **Capture:** `zwlr_screencopy_manager_v1` with `overlay_cursor = 1` so
//!   the native Linux cursor is rendered into the stream; frames are packed
//!   from `memfd`+`wl_shm` pools, LZ4-compressed, and shipped as `b"WFRM"`
//!   frames over the video plane.
//! - **Input:** `zwp_virtual_keyboard_v1` (embedded US-QWERTY XKB keymap in a
//!   memfd — pure Rust, zero libxkbcommon — with modifier tracking) +
//!   `zwlr_virtual_pointer_v1` (`motion_absolute` for 1:1 cursor alignment,
//!   buttons, scroll, frames).
//! - **Output management:** `zwlr_output_manager_v1` applies the requested
//!   `--width/--height/--scale` at startup and reconfigures the headless
//!   output on live `Resize` messages (the screencopy loop reallocates its
//!   `wl_shm` buffer automatically from the next `buffer` event).
//! - **Clipboard:** `zwlr_data_control_manager_v1` both directions
//!   (`text/plain;charset=utf-8`), deduplicated with SHA-256 so host ↔ guest
//!   never echo-loop.
//!
//! The loop is fully non-blocking: wayland events via a nonblocking socket +
//! `dispatch_pending`/`read_events`, input via an mpsc channel drained every
//! iteration with a self-pipe wakeup — `blocking_dispatch` (and its 16ms
//! input lag) is never used.

