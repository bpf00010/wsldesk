/// Apply the requested mode to the first head via
/// `enable_head → set_custom_mode(w, h, 60000) → set_scale → apply`.
fn apply_output_mode(state: &mut SessionState, qh: &QueueHandle<SessionState>) {
    let Some((width, height, scale_milli)) = state.pending_resize.take() else {
        return;
    };
    let Some(manager) = state.output_manager.clone() else {
        eprintln!("wsldesk-guest video: output manager missing; resize skipped");
        return;
    };
    let Some(serial) = state.serial else {
        state.pending_resize = Some((width, height, scale_milli));
        return;
    };
    let Some(head) = state.heads.first().cloned() else {
        state.pending_resize = Some((width, height, scale_milli));
        return;
    };

    let config = manager.create_configuration(serial, qh, ());
    let head_config = config.enable_head(&head, qh, ());
    head_config.set_custom_mode(width as i32, height as i32, 60_000);
    let scale = (scale_milli as f64 / 1000.0).max(1.0);
    head_config.set_scale(scale);
    config.apply();
    eprintln!(
        "wsldesk-guest video: output config applied: {width}x{height} scale {scale} (serial {serial}); \
         screencopy picks up the new geometry from the next buffer event"
    );
}

